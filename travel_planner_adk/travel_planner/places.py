PLACES: tuple[Place, ...] = tuple(Place(*row) for row in _ROWS)
PLACE_IDS: tuple[str, ...] = tuple(place.id for place in PLACES)
PLACES_BY_ID: dict[str, Place] = {place.id: place for place in PLACES}

if len(PLACE_IDS) != len(PLACES_BY_ID):
    raise RuntimeError("Place catalog has duplicate ids.")


def search_places(query: str, limit: int = 8) -> list[Place]:
    """Rank catalog places by words in the name, country, or summary."""
    tokens = [
        token
        for token in re.split(r"[^a-z0-9]+", query.lower())
        if len(token) > 1
    ]
    if not tokens:
        return []

    ranked: list[tuple[int, str, Place]] = []
    for place in PLACES:
        haystack = (
            f"{place.id} {place.name} {place.country} {place.summary}".lower()
        )
        hits = sum(1 for token in tokens if token in haystack)
        if hits:
            ranked.append((hits, place.name, place))
    ranked.sort(key=lambda item: (-item[0], item[1]))
    return [place for _, _, place in ranked[:limit]]


def format_places(places: list[Place]) -> str:
    if not places:
        return (
            "No catalog destinations matched. Try a city, country, or feature "
            "such as beach, safari, alps, food, or temple."
        )
    return "\n".join(
        f"{place.id}: {place.name}, {place.country}. {place.summary}"
        for place in places
    )
